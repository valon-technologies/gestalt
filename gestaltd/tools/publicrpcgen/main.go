package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/valon-technologies/gestalt/server/internal/publicrpc"
)

type serviceSpec struct {
	GRPCFile    string
	ServerIface string
	ServiceName string
}

var services = []serviceSpec{
	{
		GRPCFile:    "../../rpc/protov1/v1/app_grpc.pb.go",
		ServerIface: "AppServer",
		ServiceName: "App",
	},
	{
		GRPCFile:    "../../rpc/protov1/v1/agent_grpc.pb.go",
		ServerIface: "AgentServer",
		ServiceName: "Agent",
	},
	{
		GRPCFile:    "../../rpc/protov1/v1/workflow_grpc.pb.go",
		ServerIface: "WorkflowServer",
		ServiceName: "Workflow",
	},
}

func main() {
	output := flag.String("output", "", "output file path")
	flag.Parse()

	if *output == "" {
		flag.Usage()
		os.Exit(2)
	}

	registry, err := publicrpc.NewGeneratedRegistry()
	if err != nil {
		fmt.Fprintf(os.Stderr, "public registry: %v\n", err)
		os.Exit(1)
	}

	publicByService := map[string][]publicrpc.PublicMethodPolicy{}
	registry.Range(func(policy publicrpc.PublicMethodPolicy) {
		publicByService[policy.Service] = append(publicByService[policy.Service], policy)
	})

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gestaltd/tools/publicrpcgen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package publicrpc\n\n")
	fmt.Fprintf(&buf, "import (\n")
	fmt.Fprintf(&buf, "\t\"context\"\n\n")
	fmt.Fprintf(&buf, "\tproto \"github.com/valon-technologies/gestalt/server/rpc/protov1/v1\"\n")
	fmt.Fprintf(&buf, "\t\"google.golang.org/grpc\"\n")
	if needsEmptyImport(services, publicByService) {
		fmt.Fprintf(&buf, "\t\"google.golang.org/protobuf/types/known/emptypb\"\n")
	}
	fmt.Fprintf(&buf, ")\n\n")

	for _, service := range services {
		methods, err := parseInterfaceMethods(service.GRPCFile, service.ServerIface)
		if err != nil {
			fmt.Fprintf(os.Stderr, "parse %s: %v\n", service.ServerIface, err)
			os.Exit(1)
		}
		serviceFullName := "gestalt.provider.v1." + service.ServiceName
		publicMethods := publicByService[serviceFullName]
		if len(publicMethods) == 0 {
			continue
		}
		publicSet := make(map[string]publicrpc.PublicMethodPolicy, len(publicMethods))
		for _, policy := range publicMethods {
			publicSet[policy.Method] = policy
		}

		filtered := make([]methodSpec, 0, len(methods))
		for _, method := range methods {
			if _, ok := publicSet[method.Name]; ok {
				filtered = append(filtered, method)
			}
		}
		sort.Slice(filtered, func(i, j int) bool {
			return filtered[i].Name < filtered[j].Name
		})

		writeRegister(&buf, service, filtered)
		for _, method := range filtered {
			writeHandler(&buf, service, method)
		}
	}

	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "mkdir: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, buf.Bytes(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write: %v\n", err)
		os.Exit(1)
	}
}

type methodSpec struct {
	Name        string
	RequestType string
}

func needsEmptyImport(services []serviceSpec, publicByService map[string][]publicrpc.PublicMethodPolicy) bool {
	for _, service := range services {
		serviceFullName := "gestalt.provider.v1." + service.ServiceName
		if len(publicByService[serviceFullName]) == 0 {
			continue
		}
		methods, err := parseInterfaceMethods(service.GRPCFile, service.ServerIface)
		if err != nil {
			continue
		}
		publicSet := make(map[string]struct{}, len(publicByService[serviceFullName]))
		for _, policy := range publicByService[serviceFullName] {
			publicSet[policy.Method] = struct{}{}
		}
		for _, method := range methods {
			if _, ok := publicSet[method.Name]; !ok {
				continue
			}
			if strings.Contains(method.RequestType, "emptypb.") {
				return true
			}
		}
	}
	return false
}

func writeRegister(buf *bytes.Buffer, service serviceSpec, methods []methodSpec) {
	fmt.Fprintf(buf, "func RegisterPublic%sServer(s grpc.ServiceRegistrar, srv proto.%s) {\n", service.ServiceName, service.ServerIface)
	fmt.Fprintf(buf, "\tif t, ok := srv.(interface{ testEmbeddedByValue() }); ok {\n")
	fmt.Fprintf(buf, "\t\tt.testEmbeddedByValue()\n")
	fmt.Fprintf(buf, "\t}\n")
	fmt.Fprintf(buf, "\ts.RegisterService(&grpc.ServiceDesc{\n")
	fmt.Fprintf(buf, "\t\tServiceName: proto.%s_ServiceDesc.ServiceName,\n", service.ServiceName)
	fmt.Fprintf(buf, "\t\tHandlerType: (*proto.%s)(nil),\n", service.ServerIface)
	fmt.Fprintf(buf, "\t\tMethods: []grpc.MethodDesc{\n")
	for _, method := range methods {
		fmt.Fprintf(buf, "\t\t\t{\n")
		fmt.Fprintf(buf, "\t\t\t\tMethodName: %q,\n", method.Name)
		fmt.Fprintf(buf, "\t\t\t\tHandler:    public%s%sHandler(srv),\n", service.ServiceName, method.Name)
		fmt.Fprintf(buf, "\t\t\t},\n")
	}
	fmt.Fprintf(buf, "\t\t},\n")
	fmt.Fprintf(buf, "\t\tStreams:  []grpc.StreamDesc{},\n")
	fmt.Fprintf(buf, "\t\tMetadata: proto.%s_ServiceDesc.Metadata,\n", service.ServiceName)
	fmt.Fprintf(buf, "\t}, srv)\n")
	fmt.Fprintf(buf, "}\n\n")
}

func writeHandler(buf *bytes.Buffer, service serviceSpec, method methodSpec) {
	handlerName := fmt.Sprintf("public%s%sHandler", service.ServiceName, method.Name)
	fullMethodConst := fmt.Sprintf("proto.%s_%s_FullMethodName", service.ServiceName, method.Name)
	requestType := qualifyProtoType(method.RequestType)
	newType := strings.TrimPrefix(requestType, "*")

	fmt.Fprintf(buf, "func %s(srv proto.%s) grpc.MethodHandler {\n", handlerName, service.ServerIface)
	fmt.Fprintf(buf, "\treturn func(_ any, ctx context.Context, dec func(any) error, interceptor grpc.UnaryServerInterceptor) (any, error) {\n")
	fmt.Fprintf(buf, "\t\tin := new(%s)\n", newType)
	fmt.Fprintf(buf, "\t\tif err := dec(in); err != nil {\n")
	fmt.Fprintf(buf, "\t\t\treturn nil, err\n")
	fmt.Fprintf(buf, "\t\t}\n")
	fmt.Fprintf(buf, "\t\tfullMethod := %s\n", fullMethodConst)
	fmt.Fprintf(buf, "\t\thandler := func(ctx context.Context, req any) (any, error) {\n")
	fmt.Fprintf(buf, "\t\t\tctx = WithPublicOrigin(ctx, fullMethod)\n")
	fmt.Fprintf(buf, "\t\t\treturn srv.%s(ctx, req.(%s))\n", method.Name, requestType)
	fmt.Fprintf(buf, "\t\t}\n")
	fmt.Fprintf(buf, "\t\tif interceptor == nil {\n")
	fmt.Fprintf(buf, "\t\t\treturn handler(ctx, in)\n")
	fmt.Fprintf(buf, "\t\t}\n")
	fmt.Fprintf(buf, "\t\tinfo := &grpc.UnaryServerInfo{\n")
	fmt.Fprintf(buf, "\t\t\tServer:     srv,\n")
	fmt.Fprintf(buf, "\t\t\tFullMethod: fullMethod,\n")
	fmt.Fprintf(buf, "\t\t}\n")
	fmt.Fprintf(buf, "\t\treturn interceptor(ctx, in, info, handler)\n")
	fmt.Fprintf(buf, "\t}\n")
	fmt.Fprintf(buf, "}\n\n")
}

func qualifyProtoType(src string) string {
	src = strings.TrimSpace(src)
	if strings.HasPrefix(src, "*emptypb.") {
		return src
	}
	if strings.HasPrefix(src, "*") {
		return "*proto." + strings.TrimPrefix(src, "*")
	}
	return "proto." + src
}

func parseInterfaceMethods(path, ifaceName string) ([]methodSpec, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return nil, err
	}

	var methods []methodSpec
	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.TYPE {
			continue
		}
		for _, spec := range genDecl.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || typeSpec.Name.Name != ifaceName {
				continue
			}
			iface, ok := typeSpec.Type.(*ast.InterfaceType)
			if !ok {
				return nil, fmt.Errorf("%s is not an interface", ifaceName)
			}
			for _, method := range iface.Methods.List {
				if len(method.Names) == 0 {
					continue
				}
				name := method.Names[0].Name
				if strings.HasPrefix(name, "mustEmbedUnimplemented") {
					continue
				}
				fn, ok := method.Type.(*ast.FuncType)
				if !ok || fn.Params == nil || len(fn.Params.List) < 2 {
					continue
				}
				requestType := formatTypeExpr(fn.Params.List[1].Type)
				methods = append(methods, methodSpec{
					Name:        name,
					RequestType: requestType,
				})
			}
			return methods, nil
		}
	}
	return nil, fmt.Errorf("interface %s not found in %s", ifaceName, path)
}

func formatTypeExpr(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + formatTypeExpr(t.X)
	case *ast.SelectorExpr:
		return formatTypeExpr(t.X) + "." + t.Sel.Name
	default:
		return "any"
	}
}
