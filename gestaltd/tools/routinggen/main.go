package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

func main() {
	var (
		grpcFile     = flag.String("grpc", "", "path to *_grpc.pb.go")
		service      = flag.String("service", "", "Server interface name, e.g. IndexedDBServer")
		receiver     = flag.String("receiver", "", "routing receiver type, e.g. routingIndexedDBServer")
		binding      = flag.String("binding", "", "binding service name passed to ResolveBinding")
		packageName  = flag.String("package", "", "output Go package name")
		serverField  = flag.String("server-field", "servers", "map field name on receiver")
		serverType   = flag.String("server-type", "", "map value type, e.g. proto.IndexedDBServer")
		defaultField = flag.String("default-field", "defaultBinding", "default binding field on receiver")
		output       = flag.String("output", "", "output file path")
	)
	flag.Parse()

	if *grpcFile == "" || *service == "" || *receiver == "" || *binding == "" || *packageName == "" || *serverType == "" || *output == "" {
		flag.Usage()
		os.Exit(2)
	}

	methods, err := parseInterfaceMethods(*grpcFile, *service)
	if err != nil {
		fmt.Fprintf(os.Stderr, "parse interface: %v\n", err)
		os.Exit(1)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gestaltd/tools/routinggen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", *packageName)
	fmt.Fprintf(&buf, "import (\n")
	fmt.Fprintf(&buf, "\t\"context\"\n\n")
	fmt.Fprintf(&buf, "\tproto \"github.com/valon-technologies/gestalt/server/rpc/protov1/v1\"\n")
	if needsEmpty(methods) {
		fmt.Fprintf(&buf, "\t\"google.golang.org/protobuf/types/known/emptypb\"\n")
	}
	fmt.Fprintf(&buf, ")\n\n")

	for _, method := range methods {
		writeMethod(&buf, *receiver, *binding, *serverField, *serverType, *defaultField, qualifyMethod(method))
	}

	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "mkdir: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, buf.Bytes(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write: %v\n", err)
		os.Exit(1)
	}
}

type methodSpec struct {
	Name        string
	Params      string
	Results     string
	IsStreaming bool
}

func needsEmpty(methods []methodSpec) bool {
	for _, method := range methods {
		if strings.Contains(method.Params, "emptypb.") || strings.Contains(method.Results, "emptypb.") {
			return true
		}
	}
	return false
}

func qualifyMethod(method methodSpec) methodSpec {
	method.Params = qualifyTypes(method.Params)
	method.Results = qualifyTypes(method.Results)
	return method
}

var unqualifiedProtoType = regexp.MustCompile(`\*([A-Z][A-Za-z0-9_]*)`)

func qualifyTypes(src string) string {
	return unqualifiedProtoType.ReplaceAllString(src, "*proto.${1}")
}

func parseInterfaceMethods(path, ifaceName string) ([]methodSpec, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return nil, err
	}

	var methods []methodSpec
	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok != token.TYPE {
			continue
		}
		for _, spec := range genDecl.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || typeSpec.Name.Name != ifaceName {
				continue
			}
			iface, ok := typeSpec.Type.(*ast.InterfaceType)
			if !ok {
				return nil, fmt.Errorf("%s is not an interface", ifaceName)
			}
			for _, method := range iface.Methods.List {
				if len(method.Names) == 0 {
					continue
				}
				name := method.Names[0].Name
				if strings.HasPrefix(name, "mustEmbedUnimplemented") {
					continue
				}
				fn, ok := method.Type.(*ast.FuncType)
				if !ok {
					continue
				}
				params := formatFieldList(fn.Params)
				results := formatFieldList(fn.Results)
				isStreaming := strings.Contains(params, "grpc.BidiStreamingServer") ||
					strings.Contains(params, "grpc.ServerStreamingServer") ||
					strings.Contains(params, "grpc.ClientStreamingServer")
				if isStreaming {
					continue
				}
				methods = append(methods, methodSpec{
					Name:        name,
					Params:      params,
					Results:     results,
					IsStreaming: false,
				})
			}
			return methods, nil
		}
	}
	return nil, fmt.Errorf("interface %s not found in %s", ifaceName, path)
}

func formatFieldList(fields *ast.FieldList) string {
	if fields == nil || len(fields.List) == 0 {
		return ""
	}
	parts := make([]string, 0, len(fields.List))
	for _, field := range fields.List {
		typeName := formatTypeExpr(field.Type)
		if len(field.Names) == 0 {
			parts = append(parts, typeName)
			continue
		}
		for _, name := range field.Names {
			parts = append(parts, name.Name+" "+typeName)
		}
	}
	return strings.Join(parts, ", ")
}

func formatTypeExpr(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + formatTypeExpr(t.X)
	case *ast.SelectorExpr:
		return formatTypeExpr(t.X) + "." + t.Sel.Name
	case *ast.ArrayType:
		return "[]" + formatTypeExpr(t.Elt)
	case *ast.IndexExpr:
		return formatTypeExpr(t.X) + "[" + formatTypeExpr(t.Index) + "]"
	case *ast.IndexListExpr:
		indices := make([]string, 0, len(t.Indices))
		for _, idx := range t.Indices {
			indices = append(indices, formatTypeExpr(idx))
		}
		return formatTypeExpr(t.X) + "[" + strings.Join(indices, ", ") + "]"
	default:
		return "any"
	}
}

func writeMethod(buf *bytes.Buffer, receiver, binding, serverField, serverType, defaultField string, method methodSpec) {
	sigParams := nameParams(renameFirstContext(method.Params))
	resultTypes := normalizeResults(method.Results)

	if method.IsStreaming {
		fmt.Fprintf(buf, "func (s *%s) %s(%s) error {\n", receiver, method.Name, sigParams)
		fmt.Fprintf(buf, "\tserver, err := runtimehost.ResolveBinding(%s, %q, s.%s, s.%s)\n", contextParamName(sigParams), binding, defaultField, serverField)
		fmt.Fprintf(buf, "\tif err != nil {\n\t\treturn err\n\t}\n")
		fmt.Fprintf(buf, "\treturn server.%s(%s)\n", method.Name, callArgs(sigParams))
		fmt.Fprintf(buf, "}\n\n")
		return
	}

	fmt.Fprintf(buf, "func (s *%s) %s(%s) (%s) {\n", receiver, method.Name, sigParams, resultTypes)
	fmt.Fprintf(buf, "\tserver, err := s.server(%s)\n", contextParamName(sigParams))
	if strings.TrimSpace(resultTypes) == "error" {
		fmt.Fprintf(buf, "\tif err != nil {\n\t\treturn err\n\t}\n")
	} else {
		fmt.Fprintf(buf, "\tif err != nil {\n\t\treturn %s, err\n\t}\n", zeroReturns(resultTypes))
	}
	fmt.Fprintf(buf, "\treturn server.%s(%s)\n", method.Name, callArgs(sigParams))
	fmt.Fprintf(buf, "}\n\n")
}

func normalizeResults(results string) string {
	results = strings.TrimSpace(results)
	if results == "" {
		return "error"
	}
	return results
}

func nameParams(params string) string {
	params = strings.TrimSpace(params)
	if params == "" {
		return ""
	}
	parts := strings.Split(params, ",")
	out := make([]string, 0, len(parts))
	reqCount := 0
	for _, part := range parts {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		fields := strings.Fields(part)
		if len(fields) > 1 {
			out = append(out, part)
			continue
		}
		if strings.Contains(part, "grpc.") {
			out = append(out, "stream "+part)
			continue
		}
		reqCount++
		name := "req"
		if reqCount > 1 {
			name = fmt.Sprintf("req%d", reqCount)
		}
		out = append(out, name+" "+part)
	}
	return strings.Join(out, ", ")
}

func renameFirstContext(params string) string {
	params = strings.TrimSpace(params)
	if strings.HasPrefix(params, "context.Context") {
		rest := strings.TrimPrefix(params, "context.Context")
		rest = strings.TrimPrefix(rest, ",")
		rest = strings.TrimSpace(rest)
		if rest == "" {
			return "ctx context.Context"
		}
		return "ctx context.Context, " + rest
	}
	return params
}

func contextParamName(params string) string {
	if strings.Contains(params, "ctx context.Context") {
		return "ctx"
	}
	return firstParamName(params)
}

func callArgs(params string) string {
	params = strings.TrimSpace(params)
	if params == "" {
		return ""
	}
	names := make([]string, 0, 4)
	for _, part := range strings.Split(params, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		fields := strings.Fields(part)
		if len(fields) == 0 {
			continue
		}
		names = append(names, fields[0])
	}
	return strings.Join(names, ", ")
}

func zeroReturns(results string) string {
	parts := strings.Split(results, ",")
	zeros := make([]string, 0, len(parts)-1)
	for _, part := range parts {
		part = strings.TrimSpace(part)
		if part == "error" {
			continue
		}
		if strings.HasPrefix(part, "*") || strings.Contains(part, "[]") {
			zeros = append(zeros, "nil")
			continue
		}
		zeros = append(zeros, "nil")
	}
	return strings.Join(zeros, ", ")
}

func firstParamName(params string) string {
	params = strings.TrimSpace(params)
	if params == "" {
		return "ctx"
	}
	name := strings.Fields(strings.Split(params, ",")[0])
	if len(name) == 0 {
		return "ctx"
	}
	return name[0]
}
