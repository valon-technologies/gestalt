func runSync(args []string) error {
	fs := flag.NewFlagSet("gestaltd sync", flag.ContinueOnError)
	fs.Usage = func() { printSyncUsage(fs.Output()) }
	var configPaths repeatedStringFlag
	fs.Var(&configPaths, "config", "path to config file (repeat to layer overrides)")
	artifactsDir := fs.String("artifacts-dir", "", "path to writable prepared-artifacts directory")
	lockfilePath := fs.String("lockfile", "", "path to lockfile; defaults to gestalt.lock.json in the current working directory")
	locked := fs.Bool("locked", false, "require an existing lockfile; do not resolve new metadata")
	check := fs.Bool("check", false, "fail if artifacts would need to be materialized")
	parallelism := fs.Int("parallelism", defaultSyncParallelism(), "maximum concurrent local UI source preparations")
	cacheDir := fs.String("cache-dir", "", "path to opt-in materialized artifact cache")
	verboseLong := fs.Bool("verbose", false, "emit detailed sync diagnostics")
	verboseShort := fs.Bool("v", false, "emit detailed sync diagnostics")
	outputFormat := fs.String("output-format", syncOutputFormatText, "output format: text or json")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if fs.NArg() > 0 {
		return fmt.Errorf("unexpected arguments: %s", strings.Join(fs.Args(), " "))
	}
	if *parallelism < 1 {
		return fmt.Errorf("invalid --parallelism %d: must be at least 1", *parallelism)
	}
	if err := validateSyncOutputFormat(*outputFormat); err != nil {
		return err
	}

	outputFlags := currentCLIOutputFlags()
	verbose := outputFlags.Verbose || *verboseLong || *verboseShort
	quiet := outputFlags.Quiet
	observabilityRequested := verbose || *outputFormat == syncOutputFormatJSON
	var metrics *operator.SyncMetricsRecorder
	observability := operator.SyncObservability{}
	if observabilityRequested {
		metrics = operator.NewSyncMetricsRecorder()
		observability.Recorder = metrics
	}
	opts := operator.SyncOptions{
		Locked:        *locked,
		Parallelism:   *parallelism,
		CacheDir:      *cacheDir,
		Observability: observability,
	}

	if err := syncConfigOptions(configPaths, *lockfilePath, *artifactsDir, *check, opts, *outputFormat == syncOutputFormatJSON); err != nil {
		return err
	}

	switch {
	case *outputFormat == syncOutputFormatJSON:
		return writeSyncJSON(os.Stdout, metrics.Snapshot())
	case *outputFormat != syncOutputFormatJSON && verbose && !quiet:
		return writeSyncText(os.Stderr, metrics.Snapshot(), true)
	default:
		return nil
	}
}

func defaultSyncParallelism() int {
	return operator.DefaultSyncParallelism()
}

func runValidate(args []string) error {
	fs := flag.NewFlagSet("gestaltd validate", flag.ContinueOnError)
	fs.Usage = func() { printValidateUsage(fs.Output()) }
	var configPaths repeatedStringFlag
	fs.Var(&configPaths, "config", "path to config file (repeat to layer overrides)")
	lockfilePath := fs.String("lockfile", "", "path to lockfile; defaults to gestalt.lock.json in the current working directory")
	platform := fs.String("platform", "", "target platform for static validation, formatted os/arch")
	runtimeValidation := fs.Bool("runtime", false, "run deep runtime validation that starts configured providers")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if fs.NArg() > 0 {
		return fmt.Errorf("unexpected arguments: %s", strings.Join(fs.Args(), " "))
	}

	opts, err := parseValidateConfigOptions(*platform, *runtimeValidation)
	if err != nil {
		return err
	}
	return validateConfig(configPaths, *lockfilePath, "", opts)
}

type validateConfigOptions struct {
	Platform string
	Runtime  bool
}

func parseValidateConfigOptions(platform string, runtimeValidation bool) (validateConfigOptions, error) {
	platform = strings.TrimSpace(platform)
	if platform != "" {
		goos, goarch, err := providerpkg.ParsePlatformString(platform)
		if err != nil {
			return validateConfigOptions{}, fmt.Errorf("invalid --platform %q, expected os/arch", platform)
		}
		platform = goos + "/" + goarch
	}
	if runtimeValidation && platform != "" && platform != currentReleasePlatform() {
		return validateConfigOptions{}, fmt.Errorf("--runtime validation executes host providers; --platform must be omitted or equal the host platform %q", currentReleasePlatform())
	}
	return validateConfigOptions{Platform: platform, Runtime: runtimeValidation}, nil
}

func validateConfig(configFlags []string, lockfilePath, artifactsDir string, opts validateConfigOptions) error {
	scratchDir, err := os.MkdirTemp("", "gestaltd-validate-*")
	if err != nil {
		return fmt.Errorf("create validation scratch dir: %w", err)
	}
	defer func() { _ = os.RemoveAll(scratchDir) }()

	result, err := validateConfigAtPaths(configFlags, lockfilePath, scratchDir, opts)
	if err != nil {
		return err
	}

	logConfigSummary(result.Paths, result.Config)
	for _, w := range result.Warnings {
		currentCLIReporter().Warning(w)
	}
	currentCLIReporter().Status("config ok")
	return nil
}

func logConfigSummary(paths []string, cfg *config.Config) {
	var remoteURL, remoteToken string
	if _, r, ok := cfg.DefaultRemoteEntry(); ok && r != nil {
		remoteURL, remoteToken = r.URL, r.Token
	}
	currentCLIReporter().Verbose(formatCLIFields("config loaded",
		"config_files", paths,
		"server_port", cfg.Server.PublicListener().Port,
		"server_public_addr", cfg.Server.PublicAddr(),
		"server_management_addr", maskEmpty(cfg.Server.ManagementAddr()),
		"server_base_url", maskEmpty(cfg.Server.BaseURL),
		"server_encryption", maskSecret(cfg.Server.EncryptionKey),
		"server_remote", maskEmpty(remoteURL),
		"server_remote_token", maskSecret(remoteToken),
		"authentication_provider", selectedProviderLabel(cfg.SelectedIdentityProvider()),
		"runtime_secrets_provider", selectedProviderLabel(cfg.SelectedSecretsProvider()),
		"telemetry_provider", selectedProviderLabel(cfg.SelectedTelemetryProvider()),
	))

	for name, entry := range cfg.Apps {
		if entry != nil {
			currentCLIReporter().Verbose(formatCLIFields("integration configured", "integration", name, "type", "app"))
		}
	}

}

func formatCLIFields(message string, args ...any) string {
	var builder strings.Builder
	builder.WriteString(message)
	for i := 0; i+1 < len(args); i += 2 {
		fmt.Fprintf(&builder, " %v=%v", args[i], args[i+1])
	}
	return builder.String()
}

func providerEntryLabel(entry *config.ProviderEntry) string {
	switch {
	case entry == nil:
		return "(not set)"
	case entry.HasReleaseMetadataSource():
		return entry.SourceReleaseLocation()
	case entry.HasLocalSource():
		return entry.SourcePath()
	case entry.Source.IsBuiltin():
		return entry.Source.Builtin
	default:
		return "custom"
	}
}

func selectedProviderLabel(_ string, entry *config.ProviderEntry, err error) string {
	if err != nil {
		return "(invalid)"
	}
	return providerEntryLabel(entry)
}

func maskSecret(s string) string {
	if s == "" {
		return "(not set)"
	}
	return "***"
}

func maskEmpty(s string) string {
	if s == "" {
		return "(not set)"
	}
	return s
}

func canonicalPublicURL(cfg *config.Config) string {
	if cfg == nil {
		return ""
	}
	listener := cfg.Server.PublicListener()
	if baseURL := strings.TrimRight(strings.TrimSpace(cfg.Server.BaseURL), "/"); baseURL != "" {
		if updated := loopbackBaseURLWithPort(baseURL, listener.Port); updated != "" {
			return updated
		}
		return baseURL
	}
	host := strings.TrimSpace(listener.Host)
	if host == "" || host == "0.0.0.0" || host == "::" || host == "[::]" {
		host = "localhost"
	}
	return "http://" + net.JoinHostPort(host, strconv.Itoa(listener.Port))
}

func loopbackBaseURLWithPort(raw string, port int) string {
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Host == "" {
		return ""
	}
	host := parsed.Hostname()
	if !actionableLoopbackHost(host) {
		return ""
	}
	parsed.Host = net.JoinHostPort("localhost", strconv.Itoa(port))
	return strings.TrimRight(parsed.String(), "/")
}

func actionableLoopbackHost(host string) bool {
	switch strings.TrimSpace(host) {
	case "", "localhost", "127.0.0.1", "::1":
		return true
	default:
		return false
	}
}

