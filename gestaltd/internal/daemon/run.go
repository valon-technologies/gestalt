func runServeCommand(name string, usage func(io.Writer), args []string, opts serveCommandOptions, gestaltdVersion string) error {
	fs := flag.NewFlagSet(name, flag.ContinueOnError)
	fs.Usage = func() { usage(fs.Output()) }
	var configPaths repeatedStringFlag
	fs.Var(&configPaths, "config", "path to config file (repeat to layer overrides)")
	artifactsDir := fs.String("artifacts-dir", "", "path to writable prepared-artifacts directory")
	lockfilePath := fs.String("lockfile", "", "path to lockfile; defaults to gestalt.lock.json in the current working directory")
	portFlag := fs.Int("port", 0, "public listener port; overrides server.public.port. If in use, gestaltd tries the next free port unless --port was given explicitly")
	remoteFlag := fs.String("remote", "", "remote gestaltd URL; overrides server.remote")
	remoteTokenFlag := fs.String("remote-token", "", "bearer token for remote gestaltd; overrides server.remoteToken")
	var lockedFlag *bool
	var noSyncFlag *bool
	if opts.allowLocked {
		lockedFlag = fs.Bool("locked", false, "require a fresh lockfile; do not re-resolve metadata")
		noSyncFlag = fs.Bool("no-sync", false, "do not materialize artifacts; serve pinned artifacts as-is")
	}
	if err := parseInterspersed(fs, args); err != nil {
		return err
	}
	positionals := fs.Args()
	if !opts.allowProviderLocal && len(positionals) > 0 {
		return fmt.Errorf("unexpected arguments: %s", strings.Join(positionals, " "))
	}

	var resolvedConfigPaths []string
	if opts.autoGenerateDefaultConfig {
		var err error
		resolvedConfigPaths, err = operator.ResolveStartConfigPaths([]string(configPaths))
		if err != nil {
			return err
		}
	} else {
		resolvedConfigPaths = operator.ResolveConfigPaths([]string(configPaths))
	}

	locked := false
	noSync := false
	if lockedFlag != nil {
		locked = *lockedFlag
	}
	if noSyncFlag != nil {
		noSync = *noSyncFlag
	}
	if noSync && !locked {
		return fmt.Errorf("--no-sync requires --locked")
	}

	if opts.allowProviderLocal {
		ranProviderLocal, err := maybeRunServeProviderLocal(serveProviderLocalOptions{
			ConfigPaths:     []string(configPaths),
			Paths:           positionals,
			Port:            flagIntValue(portFlag),
			ArtifactsDir:    *artifactsDir,
			LockfilePath:    *lockfilePath,
			Locked:          locked,
			NoSync:          noSync,
			Remote:          *remoteFlag,
			RemoteToken:     *remoteTokenFlag,
			Dev:             opts.dev,
			LockedAllowed:   lockedFlag != nil,
			GestaltdVersion: gestaltdVersion,
		})
		if ranProviderLocal || err != nil {
			return err
		}
	}
	env, err := setupBootstrapWithConfigPaths(resolvedConfigPaths, *lockfilePath, *artifactsDir, locked, noSync, *remoteFlag, *remoteTokenFlag, opts.dev)
	if err != nil {
		return err
	}
	if err := resolveServePort(env.Config, flagIntValue(portFlag)); err != nil {
		env.Close()
		return err
	}
	return runServerWithReady(env, gestaltdVersion, func() {
		currentCLIReporter().Status("gestaltd ready: " + canonicalPublicURL(env.Config))
	})
}

type serveProviderLocalOptions struct {
	ConfigPaths     []string
	Paths           []string
	Port            int
	ArtifactsDir    string
	LockfilePath    string
	Locked          bool
	NoSync          bool
	Remote          string
	RemoteToken     string
	Dev             bool
	LockedAllowed   bool
	GestaltdVersion string
}

func maybeRunServeProviderLocal(opts serveProviderLocalOptions) (bool, error) {
	paths := make([]string, 0, len(opts.Paths))
	for _, path := range opts.Paths {
		if trimmed := strings.TrimSpace(path); trimmed != "" {
			paths = append(paths, trimmed)
		}
	}
	if len(paths) == 0 {
		return false, nil
	}
	if opts.LockedAllowed && opts.Locked && len(opts.ConfigPaths) == 0 {
		return true, fmt.Errorf("--locked requires --config when serving local PATH arguments")
	}
	if len(opts.ConfigPaths) == 0 && (opts.ArtifactsDir != "" || opts.LockfilePath != "") {
		return true, fmt.Errorf("--lockfile and --artifacts-dir require --config when serving local PATH arguments")
	}
	return true, runServeProviderLocal(providerLocalCommandOptions{
		Paths:           paths,
		ConfigPaths:     opts.ConfigPaths,
		Port:            opts.Port,
		Locked:          opts.Locked,
		NoSync:          opts.NoSync,
		Remote:          opts.Remote,
		RemoteToken:     opts.RemoteToken,
		Dev:             opts.Dev,
		ArtifactsDir:    opts.ArtifactsDir,
		LockfilePath:    opts.LockfilePath,
		GestaltdVersion: opts.GestaltdVersion,
	})
}

func flagIntValue(flag *int) int {
	if flag == nil {
		return 0
	}
	return *flag
}

func runServerWithReady(env *bootstrapEnv, gestaltdVersion string, onReady func()) error {
	defer env.Close()
	return server.RunWithReady(env.Ctx, env.Config, env.Result, gestaltdVersion, onReady)
}

const maxServePortScan = 100

// resolveServePort sets cfg.Server.Public.Port to a bindable port. When
// portFlag is non-zero it pins that port and fails if it is in use;
// otherwise it starts from the configured port and tries the next free
// one, logging any move.
func resolveServePort(cfg *config.Config, portFlag int) error {
	requested := portFlag
	if requested == 0 {
		requested = cfg.Server.PublicListener().Port
	}
	host := cfg.Server.Public.Host
	for offset := 0; ; offset++ {
		if portFlag != 0 && offset > 0 {
			return fmt.Errorf("port %d is in use; free it or specify a different port", requested)
		}
		if offset > maxServePortScan {
			return fmt.Errorf("no free port found near %d; specify --port or free a port", requested)
		}
		candidate := requested + offset
		l, err := net.Listen("tcp", net.JoinHostPort(host, strconv.Itoa(candidate)))
		if err != nil {
			continue
		}
		_ = l.Close()
		if candidate != requested {
			currentCLIReporter().Warning(fmt.Sprintf("gestaltd port in use; using next free port (requested %d, using %d)", requested, candidate))
		}
		cfg.Server.Public.Port = candidate
		return nil
	}
}

