package publicrpc

import (
	"fmt"
	"sort"
	"strings"

	"github.com/valon-technologies/gestalt/sdk/tools/sdkgen/internal/model"
	"github.com/valon-technologies/gestalt/sdk/tools/sdkgen/internal/publicsurface"
)

// EmitRESTGateway writes gestaltd/internal/publicrpc/rest_gateway_gen.go from the manifest.
func EmitRESTGateway(schema *model.Schema) (string, error) {
	plan, err := publicsurface.PrepareEmit(schema)
	if err != nil {
		return "", err
	}
	services := map[string]struct{}{}
	for _, pm := range plan.Methods {
		if pm.REST == nil {
			continue
		}
		services[pm.Service] = struct{}{}
	}
	names := make([]string, 0, len(services))
	for name := range services {
		names = append(names, name)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("// Code generated by sdkgen. DO NOT EDIT.\n\n")
	b.WriteString("package publicrpc\n\n")
	b.WriteString("// restGatewayServices lists public services exposed on the /api/v2 REST gateway.\n")
	b.WriteString("// Keys are fully qualified gRPC service names matching grpc.ServiceDesc.ServiceName.\n")
	b.WriteString("var restGatewayServices = map[string]struct{}{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q: {},\n", name)
	}
	b.WriteString("}\n")
	return b.String(), nil
}
