package publicsurface

import (
	"encoding/json"
	"sort"

	"github.com/valon-technologies/gestalt/sdk/tools/sdkgen/internal/model"
)

const contractSchemaVersion = 1

// Contract is the language-neutral public surface snapshot.
type Contract struct {
	Generated     string            `json:"_generated"`
	SchemaVersion int               `json:"schemaVersion"`
	Counts        ContractCounts    `json:"counts"`
	Services      []ContractService `json:"services"`
}

// ContractCounts summarizes the public surface.
type ContractCounts struct {
	Services         int `json:"services"`
	GRPCUnaryMethods int `json:"grpcUnaryMethods"`
	RESTMethods      int `json:"restMethods"`
}

// ContractService is one public service in the contract.
type ContractService struct {
	Name     string           `json:"name"`
	FullName string           `json:"fullName"`
	Methods  []ContractMethod `json:"methods"`
}

// ContractMethod is one public unary method in the contract.
type ContractMethod struct {
	Name        string        `json:"name"`
	FullMethod  string        `json:"fullMethod"`
	Input       string        `json:"input,omitempty"`
	Output      string        `json:"output,omitempty"`
	InputEmpty  bool          `json:"inputEmpty,omitempty"`
	OutputEmpty bool          `json:"outputEmpty,omitempty"`
	Transports  []string      `json:"transports"`
	Fill        []string      `json:"fill"`
	Reject      []string      `json:"reject"`
	HTTP        *ContractHTTP `json:"http,omitempty"`
}

// ContractHTTP is the REST binding for a public method.
type ContractHTTP struct {
	Verb        string   `json:"verb"`
	Path        string   `json:"path"`
	Body        string   `json:"body"`
	PathFields  []string `json:"pathFields"`
	QueryFields []string `json:"queryFields"`
}

// BuildContract constructs the contract from a validated schema.
func BuildContract(schema *model.Schema) (*Contract, error) {
	if err := Validate(schema); err != nil {
		return nil, err
	}
	view := Build(schema)
	grpcMethods, err := ParseMethods(schema, view, ProjectionGRPC)
	if err != nil {
		return nil, err
	}
	restMethods, err := ParseMethods(schema, view, ProjectionREST)
	if err != nil {
		return nil, err
	}
	restByFull := map[string]PublicMethod{}
	for _, pm := range restMethods {
		restByFull[pm.FullMethod] = pm
	}

	contract := &Contract{
		Generated:     "Code generated by sdkgen. DO NOT EDIT.",
		SchemaVersion: contractSchemaVersion,
		Counts: ContractCounts{
			Services:         len(view.Services),
			GRPCUnaryMethods: len(grpcMethods),
			RESTMethods:      len(restMethods),
		},
	}
	for _, svc := range view.Services {
		cs := ContractService{
			Name:     svc.Name,
			FullName: svc.FullName,
		}
		for _, m := range svc.PublicMethods {
			pm, err := parseMethod(schema, svc.Service, m)
			if err != nil {
				return nil, err
			}
			cm := contractMethod(pm)
			if restPM, ok := restByFull[pm.FullMethod]; ok {
				cm.HTTP = contractHTTP(restPM.REST)
			}
			cs.Methods = append(cs.Methods, cm)
		}
		contract.Services = append(contract.Services, cs)
	}
	return contract, nil
}

func contractMethod(pm PublicMethod) ContractMethod {
	cm := ContractMethod{
		Name:        pm.Method,
		FullMethod:  pm.FullMethod,
		InputEmpty:  pm.InputIsEmpty,
		OutputEmpty: pm.OutputIsEmpty,
		Fill:        nonNilStrings(publicsurfaceFieldNames(pm.ServerFilled)),
		Reject:      nonNilStrings(publicsurfaceFieldNames(pm.Rejected)),
	}
	if pm.Input != nil {
		cm.Input = pm.Input.FullName
	}
	if pm.Output != nil {
		cm.Output = pm.Output.FullName
	}
	cm.Transports = []string{"grpc"}
	if pm.REST != nil {
		cm.Transports = append(cm.Transports, "rest")
	}
	sort.Strings(cm.Transports)
	return cm
}

func publicsurfaceFieldNames(fields []PublicField) []string {
	out := make([]string, len(fields))
	for i, f := range fields {
		out[i] = f.Name
	}
	return out
}

func contractHTTP(rule *RESTRule) *ContractHTTP {
	if rule == nil {
		return nil
	}
	body := ""
	if rule.Body == BodyStar {
		body = "*"
	}
	return &ContractHTTP{
		Verb:        rule.Verb,
		Path:        rule.PathTemplate,
		Body:        body,
		PathFields:  nonNilStrings(FieldNames(rule.PathFields)),
		QueryFields: nonNilStrings(FieldNames(rule.QueryFields)),
	}
}

func nonNilStrings(values []string) []string {
	if values == nil {
		return []string{}
	}
	return values
}

// MarshalContract returns deterministic JSON bytes for the contract.
func MarshalContract(contract *Contract) ([]byte, error) {
	return json.MarshalIndent(contract, "", "  ")
}
