import { readFileSync, writeFileSync } from "node:fs";
import * as ts from "typescript";

const siblingNativeModules = new Set([
  "./app.ts",
  "./agent.ts",
  "./authorization.ts",
  "./identity.ts",
  "./workflow.ts",
]);

/**
 * Extracts type-only exports from sdkgen service modules for gestalt-web runtime.
 * Strips service client runtime imports that pull connect-node into the browser graph.
 */
export function extractNativeTypes(appSource: string): string {
  const sourceFile = ts.createSourceFile(
    "module.ts",
    appSource,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );

  const chunks: string[] = [];
  for (const statement of sourceFile.statements) {
    if (!isTypeOnlyExport(statement)) {
      continue;
    }
    chunks.push(appSource.slice(statement.getFullStart(), statement.getEnd()));
  }

  const siblingImports = collectSiblingTypeImports(sourceFile, appSource);
  const body = chunks.join("").trimStart().trimEnd();

  return [
    "// Code generated by sync-web-runtime. DO NOT EDIT.",
    "",
    'import type { JsonObject, JsonValue } from "@bufbuild/protobuf";',
    ...(siblingImports.length > 0 ? ["", ...siblingImports] : []),
    ...(body.length > 0 ? ["", body] : []),
    "",
  ].join("\n");
}

function collectSiblingTypeImports(
  sourceFile: ts.SourceFile,
  source: string,
): string[] {
  const imports: string[] = [];
  for (const statement of sourceFile.statements) {
    if (!ts.isImportDeclaration(statement) || !statement.importClause) {
      continue;
    }
    const spec = statement.moduleSpecifier;
    if (!ts.isStringLiteral(spec) || !siblingNativeModules.has(spec.text)) {
      continue;
    }
    if (!isTypeOnlyImport(statement.importClause)) {
      continue;
    }
    imports.push(source.slice(statement.getFullStart(), statement.getEnd()).trim());
  }
  return imports;
}

function isTypeOnlyImport(clause: ts.ImportClause): boolean {
  if (clause.isTypeOnly) {
    return true;
  }
  if (!clause.namedBindings || !ts.isNamedImports(clause.namedBindings)) {
    return false;
  }
  return clause.namedBindings.elements.every((element) => element.isTypeOnly);
}

function isTypeOnlyExport(statement: ts.Statement): boolean {
  const modifiers = ts.canHaveModifiers(statement)
    ? ts.getModifiers(statement)
    : undefined;
  if (!modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)) {
    return false;
  }

  if (ts.isInterfaceDeclaration(statement) || ts.isTypeAliasDeclaration(statement)) {
    return true;
  }

  if (ts.isVariableStatement(statement)) {
    return statement.declarationList.declarations.every((declaration) =>
      isConstObjectLiteral(declaration.initializer),
    );
  }

  return false;
}

function isConstObjectLiteral(initializer: ts.Expression | undefined): boolean {
  if (!initializer) {
    return false;
  }
  if (ts.isObjectLiteralExpression(initializer)) {
    return true;
  }
  if (ts.isAsExpression(initializer)) {
    return ts.isObjectLiteralExpression(initializer.expression);
  }
  return false;
}

if (import.meta.main) {
  const [inputPath, outputPath] = process.argv.slice(2);
  if (!inputPath || !outputPath) {
    console.error("usage: extract-native-types.ts <module.ts> <output.ts>");
    process.exit(1);
  }
  const source = readFileSync(inputPath, "utf8");
  writeFileSync(outputPath, extractNativeTypes(source));
}
