import { readFileSync, writeFileSync } from "node:fs";
import * as ts from "typescript";

/**
 * Extracts type-only exports from sdkgen's app.ts for gestalt-web runtime.
 * Strips service client runtime imports that pull connect-node into the browser graph.
 */
export function extractNativeTypes(appSource: string): string {
  const sourceFile = ts.createSourceFile(
    "app.ts",
    appSource,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );

  const chunks: string[] = [];
  for (const statement of sourceFile.statements) {
    if (!isTypeOnlyExport(statement)) {
      continue;
    }
    chunks.push(appSource.slice(statement.getFullStart(), statement.getEnd()));
  }

  return [
    "// Code generated by sync-web-runtime. DO NOT EDIT.",
    "",
    'import type { JsonObject, JsonValue } from "@bufbuild/protobuf";',
    "",
    chunks.join("").trimStart().trimEnd(),
    "",
  ].join("\n");
}

function isTypeOnlyExport(statement: ts.Statement): boolean {
  const modifiers = ts.canHaveModifiers(statement)
    ? ts.getModifiers(statement)
    : undefined;
  if (!modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)) {
    return false;
  }

  if (ts.isInterfaceDeclaration(statement) || ts.isTypeAliasDeclaration(statement)) {
    return true;
  }

  if (ts.isVariableStatement(statement)) {
    return statement.declarationList.declarations.every((declaration) =>
      isConstObjectLiteral(declaration.initializer),
    );
  }

  return false;
}

function isConstObjectLiteral(initializer: ts.Expression | undefined): boolean {
  if (!initializer) {
    return false;
  }
  if (ts.isObjectLiteralExpression(initializer)) {
    return true;
  }
  if (ts.isAsExpression(initializer)) {
    return ts.isObjectLiteralExpression(initializer.expression);
  }
  return false;
}

if (import.meta.main) {
  const [inputPath, outputPath] = process.argv.slice(2);
  if (!inputPath || !outputPath) {
    console.error("usage: extract-native-types.ts <app.ts> <native-types.ts>");
    process.exit(1);
  }
  const source = readFileSync(inputPath, "utf8");
  writeFileSync(outputPath, extractNativeTypes(source));
}
