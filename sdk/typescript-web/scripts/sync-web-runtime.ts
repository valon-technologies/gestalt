import { cpSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import { extractNativeTypes } from "./extract-native-types.ts";

const gestaltSrcRoot = join(import.meta.dir, "..", "..", "typescript", "src");
const webRuntimeRoot = join(import.meta.dir, "..", "src", "client", "runtime");

const restServiceSources = [
  "app.ts",
  "agent.ts",
  "workflow.ts",
  "identity.ts",
  "authorization.ts",
] as const;

const runtimePaths = [
  "invoke_support.ts",
  "rpc_support.ts",
  "internal/codec/app.ts",
  "internal/codec/agent.ts",
  "internal/codec/workflow.ts",
  "internal/codec/identity.ts",
  "internal/codec/authorization.ts",
  "internal/codec/support.ts",
  "internal/gen",
] as const;

const nativeModuleRewrites = [
  "../../app.ts",
  "../../agent.ts",
  "../../workflow.ts",
  "../../identity.ts",
  "../../authorization.ts",
] as const;

function patchRuntimeImports(source: string): string {
  let patched = source;
  for (const modulePath of nativeModuleRewrites) {
    patched = patched.replaceAll(modulePath, "../../native-types.ts");
  }
  return patched;
}

rmSync(webRuntimeRoot, { recursive: true, force: true });
mkdirSync(webRuntimeRoot, { recursive: true });

for (const relativePath of runtimePaths) {
  const sourcePath = join(gestaltSrcRoot, relativePath);
  const targetPath = join(webRuntimeRoot, relativePath);
  if (statSync(sourcePath).isDirectory()) {
    cpSync(sourcePath, targetPath, { recursive: true });
    continue;
  }
  mkdirSync(dirname(targetPath), { recursive: true });
  writeFileSync(targetPath, patchRuntimeImports(readFileSync(sourcePath, "utf8")));
}

const nativeTypeChunks = restServiceSources.map((relativePath) => {
  const extracted = extractNativeTypes(
    readFileSync(join(gestaltSrcRoot, relativePath), "utf8"),
  );
  return extracted.split("\n").slice(4).join("\n").trim();
});
writeFileSync(
  join(webRuntimeRoot, "native-types.ts"),
  [
    "// Code generated by sync-web-runtime. DO NOT EDIT.",
    "",
    'import type { JsonInput, JsonObjectInput } from "./rpc_support.ts";',
    "",
    nativeTypeChunks.filter(Boolean).join("\n\n"),
    "",
  ].join("\n"),
);
